"""CLI entry point to run a single agent end-to-end (used by workflows/demo).

Usage:
    python scripts/run_agent.py --agent test_quality
    python scripts/run_agent.py --agent pipeline_optimizer
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from agents.agent_effectiveness.agent import AgentEffectivenessAgent  # noqa: E402
from agents.base import AgentContext, BaseAgent  # noqa: E402
from agents.build_performance.agent import BuildPerformanceAgent  # noqa: E402
from agents.documentation_drift.agent import DocumentationDriftAgent  # noqa: E402
from agents.failure_analysis.agent import FailureAnalysisAgent  # noqa: E402
from agents.flaky_test.agent import FlakyTestAgent  # noqa: E402
from agents.merge_conflict.agent import MergeConflictAgent  # noqa: E402
from agents.orchestrator.orchestrator import AgentOrchestrator  # noqa: E402
from agents.pipeline_optimizer.agent import PipelineOptimizerAgent  # noqa: E402
from agents.supply_chain.agent import SupplyChainAgent  # noqa: E402
from agents.test_impact.agent import TestImpactAgent  # noqa: E402
from agents.test_quality.agent import TestQualityAgent  # noqa: E402
from scripts.collect_pipeline_context import collect_context  # noqa: E402

AGENTS: dict[str, type[BaseAgent]] = {
    "test_quality": TestQualityAgent,
    "failure_analysis": FailureAnalysisAgent,
    "merge_conflict": MergeConflictAgent,
    "supply_chain": SupplyChainAgent,
    "pipeline_optimizer": PipelineOptimizerAgent,
    "flaky_test": FlakyTestAgent,
    "build_performance": BuildPerformanceAgent,
    "test_impact": TestImpactAgent,
    "documentation_drift": DocumentationDriftAgent,
    "agent_effectiveness": AgentEffectivenessAgent,
}


def main() -> int:
    """Run the requested agent against locally collected context."""
    parser = argparse.ArgumentParser(description="Run a single evolutionary-cicd agent.")
    parser.add_argument(
        "--agent",
        choices=[*sorted(AGENTS), "all"],
        required=True,
        help="Agent to run, or 'all' to run every agent and file/assign issues",
    )
    parser.add_argument("--context-file", type=Path, help="JSON context generated by the collector")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--demo", action="store_true", help="Force write-free dry-run output")
    mode.add_argument(
        "--live",
        action="store_true",
        help="Explicit live mode; requires AGENT_ALLOW_LIVE=true",
    )
    args = parser.parse_args()

    if args.demo:
        os.environ["AGENT_DRY_RUN"] = "true"
    if args.live:
        if os.environ.get("AGENT_ALLOW_LIVE", "").lower() != "true":
            parser.error("--live requires AGENT_ALLOW_LIVE=true as explicit authorization")
        if not os.environ.get("GITHUB_TOKEN") or not os.environ.get("GITHUB_REPOSITORY"):
            parser.error("--live requires GITHUB_TOKEN and GITHUB_REPOSITORY")
        os.environ["AGENT_DRY_RUN"] = "false"

    if args.context_file:
        try:
            context_data = json.loads(args.context_file.read_text(encoding="utf-8"))
        except FileNotFoundError:
            parser.error(f"--context-file not found: {args.context_file}")
        except json.JSONDecodeError as exc:
            parser.error(f"--context-file is not valid JSON: {exc}")
    else:
        context_data = collect_context()
    context = AgentContext.model_validate(context_data)

    names = sorted(AGENTS) if args.agent == "all" else [args.agent]
    orchestrator = AgentOrchestrator()
    exit_code = 0
    for name in names:
        print(f"=== {name} ===")
        exit_code |= _run_one(orchestrator, AGENTS[name](), context, args)
    return exit_code


def _run_one(
    orchestrator: AgentOrchestrator,
    agent: BaseAgent,
    context: AgentContext,
    args: argparse.Namespace,
) -> int:
    """Run one agent through the orchestrator and print its outcome."""
    result = orchestrator.run_agent(agent, context)

    print(f"success={result.success}")
    print(result.message)
    issue_result = result.artifacts.get("issue_result")
    if issue_result is not None:
        print(f"issue_result={json.dumps(issue_result, sort_keys=True)}")
    proposal_data = result.artifacts.get("issue_proposal")
    if proposal_data and (args.demo or args.live):
        from agents.issue_proposals import IssueProposal
        from agents.orchestrator.orchestrator import (
            load_agent_permissions,
            load_approval_rules,
        )

        proposal = IssueProposal.model_validate(proposal_data)
        policy = load_approval_rules().get("issue_policy", {}).get("agents", {})
        agent_policy = policy.get(proposal.source_agent, {})
        permitted = bool(
            load_agent_permissions().get(proposal.source_agent, {}).get("assign_copilot", False)
            and agent_policy.get("assign_copilot", agent_policy.get("auto_assign_copilot", False))
            and proposal.assign_to_copilot
        )
        print("--- Proposed GitHub Issue ---")
        print(proposal.render_markdown())
        print(f"copilot_assignment_permitted={str(permitted).lower()}")
        print(f"simulated_outcome={'live' if args.live else 'dry-run'}")
    elif args.demo:
        print("simulated_outcome=no_action")
        decision = result.artifacts.get("decision", {})
        if decision.get("arguments"):
            print(
                "analysis_details=" + json.dumps(decision["arguments"], sort_keys=True, default=str)
            )

    return 0 if result.success else 1


if __name__ == "__main__":
    raise SystemExit(main())
